package sims.dto.carriere;

public class TypeCarriereDTO {

    // Attributs
    private String code;
    private String nom;

    // Constructeurs
    public TypeCarriereDTO() {
    }

    // Getters et Setters
    public String getCode() {
        return code;
    }
    public void setCode(String code) {
        this.code = code;
    }
    public String getNom() {
        return nom;
    }
    public void setNom(String nom) {
        this.nom = nom;
    }
}